const { withAppBuildGradle } = require("expo/config-plugins");

const PLUGIN_MARKER = "// HanabiCode release signing (generated by with-android-release-signing)";
const SIGNING_PROPERTY_NAMES = {
  storeFile: "HANABICODE_UPLOAD_STORE_FILE",
  storePassword: "HANABICODE_UPLOAD_STORE_PASSWORD",
  keyAlias: "HANABICODE_UPLOAD_KEY_ALIAS",
  keyPassword: "HANABICODE_UPLOAD_KEY_PASSWORD",
};

function findBlock(source, blockName, startIndex = 0) {
  const pattern = new RegExp(`\\b${blockName}\\s*\\{`, "g");
  pattern.lastIndex = startIndex;
  const match = pattern.exec(source);
  if (!match) {
    throw new Error(`Could not find ${blockName} block in Android app build.gradle`);
  }

  const openBrace = source.indexOf("{", match.index);
  let depth = 0;
  for (let index = openBrace; index < source.length; index += 1) {
    if (source[index] === "{") depth += 1;
    if (source[index] === "}") depth -= 1;
    if (depth === 0) {
      return { start: match.index, openBrace, closeBrace: index };
    }
  }

  throw new Error(`Could not find closing brace for ${blockName} block`);
}

function configureAndroidReleaseSigning(source) {
  if (source.includes(PLUGIN_MARKER)) {
    return source;
  }

  const androidBlock = findBlock(source, "android");
  let configured = `${source.slice(0, androidBlock.start)}${PLUGIN_MARKER}
def hanabicodeReleaseStoreFile = findProperty("${SIGNING_PROPERTY_NAMES.storeFile}")
def hanabicodeReleaseStorePassword = findProperty("${SIGNING_PROPERTY_NAMES.storePassword}")
def hanabicodeReleaseKeyAlias = findProperty("${SIGNING_PROPERTY_NAMES.keyAlias}")
def hanabicodeReleaseKeyPassword = findProperty("${SIGNING_PROPERTY_NAMES.keyPassword}")
def hanabicodeReleaseSigningConfigured = [
    hanabicodeReleaseStoreFile,
    hanabicodeReleaseStorePassword,
    hanabicodeReleaseKeyAlias,
    hanabicodeReleaseKeyPassword,
].every { value -> value != null && !value.toString().trim().isEmpty() }

${source.slice(androidBlock.start)}`;

  const configuredAndroidBlock = findBlock(configured, "android");
  const signingConfigsBlock = findBlock(
    configured,
    "signingConfigs",
    configuredAndroidBlock.openBrace,
  );
  const signingConfigBody = configured.slice(
    signingConfigsBlock.openBrace + 1,
    signingConfigsBlock.closeBrace,
  );
  if (/\brelease\s*\{/.test(signingConfigBody)) {
    throw new Error("Android app build.gradle already has a release signing config");
  }

  const releaseSigningConfig = `
        release {
            if (hanabicodeReleaseSigningConfigured) {
                storeFile file(hanabicodeReleaseStoreFile)
                storePassword hanabicodeReleaseStorePassword
                keyAlias hanabicodeReleaseKeyAlias
                keyPassword hanabicodeReleaseKeyPassword
            }
        }
    `;
  configured = `${configured.slice(0, signingConfigsBlock.closeBrace)}${releaseSigningConfig}${configured.slice(signingConfigsBlock.closeBrace)}`;

  const buildTypesBlock = findBlock(configured, "buildTypes", configuredAndroidBlock.openBrace);
  const releaseBuildType = findBlock(configured, "release", buildTypesBlock.openBrace);
  if (releaseBuildType.closeBrace > buildTypesBlock.closeBrace) {
    throw new Error("Could not find release build type inside buildTypes block");
  }

  const releaseBuildBody = configured.slice(
    releaseBuildType.openBrace + 1,
    releaseBuildType.closeBrace,
  );
  const debugSigningPattern = /signingConfig\s+signingConfigs\.debug/;
  if (!debugSigningPattern.test(releaseBuildBody)) {
    throw new Error("Could not replace the generated debug signing config for release builds");
  }

  const updatedReleaseBuildBody = releaseBuildBody.replace(
    debugSigningPattern,
    "signingConfig signingConfigs.release",
  );
  configured = `${configured.slice(0, releaseBuildType.openBrace + 1)}${updatedReleaseBuildBody}${configured.slice(releaseBuildType.closeBrace)}`;
  return configured;
}

function withAndroidReleaseSigning(config) {
  return withAppBuildGradle(config, (modConfig) => {
    if (modConfig.modResults.language !== "groovy") {
      throw new Error("HanabiCode Android release signing requires a Groovy app build.gradle");
    }
    modConfig.modResults.contents = configureAndroidReleaseSigning(modConfig.modResults.contents);
    return modConfig;
  });
}

module.exports = withAndroidReleaseSigning;
module.exports.configureAndroidReleaseSigning = configureAndroidReleaseSigning;
module.exports.SIGNING_PROPERTY_NAMES = SIGNING_PROPERTY_NAMES;
